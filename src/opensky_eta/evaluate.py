"""Comparison of the saved models: `python -m opensky_eta.evaluate`.

Loads the three selected models from `data/models/`, computes the metrics of notebook 04 on the
validation flights, next to the two baselines, with the paired bootstrap over the flights, prints
the tables and writes them to `reports/validation_results.md`. The test flights are not used.
"""
import joblib
import numpy as np
import pandas as pd

from opensky_eta.config import (
    BOOSTING_MODEL_PATH, FEATURES_PATH, FLIGHT_KEY, LABEL, LINEAR_MODEL_PATH, PHASE_TO_SEGMENT,
    PROJECT_DIR, REPORTS_DIR, SEGMENT_MODELS_PATH,
)
from opensky_eta.evaluation import bootstrap_comparison, evaluate
from opensky_eta.models import predict_selected_models

REFERENCE = "Per segment, MAE loss"  # the best linear model: the bar to beat (notebook 05)


def load_selected_models():
    """The three selected models saved by `python -m opensky_eta.train` (or by notebooks 04 and 05)."""
    return {
        "Linear, MAE loss": joblib.load(LINEAR_MODEL_PATH),
        "Per segment, MAE loss": joblib.load(SEGMENT_MODELS_PATH),
        "Gradient boosting, MAE loss": joblib.load(BOOSTING_MODEL_PATH),
    }


def compare_models(models, features, split="validation"):
    """Metrics table and paired bootstrap table of the baselines and the selected models on `split`."""
    train, rows = features[features["split"] == "train"], features[features["split"] == split]
    y, segment = rows[LABEL], rows["phase_of_flight"].map(PHASE_TO_SEGMENT)
    flight = rows.groupby(FLIGHT_KEY, sort=False).ngroup().to_numpy()

    predictions = {
        "Constant (train median)": np.full(len(rows), train[LABEL].median()),
        "Naive: distance / speed": rows["naive_time_to_arrival_s"].to_numpy(),
        **predict_selected_models(models, rows),
    }
    metrics = pd.DataFrame({name: evaluate(y, prediction, segment) for name, prediction in predictions.items()}).T
    bootstrap = bootstrap_comparison(y, {name: predictions[name] for name in list(predictions)[1:]},
                                     flight, reference=REFERENCE)
    return metrics, bootstrap


def to_markdown(table):
    """A small markdown table (no extra dependency)."""
    table = table.reset_index().astype(str)
    lines = ["| " + " | ".join(table.columns) + " |", "|" + "---|" * len(table.columns)]
    lines += ["| " + " | ".join(row) + " |" for row in table.to_numpy()]
    return "\n".join(lines)


def report(models, features, split="validation"):
    """Prints the comparison tables and writes them to reports/<split>_results.md."""
    metrics, bootstrap = compare_models(models, features, split)
    pd.set_option("display.width", 200)
    pd.set_option("display.max_columns", 20)
    print(f"\nErrors on the {split} flights (minutes):")
    print(metrics.round(2).to_string())
    print(f"\nMAE with 95 % confidence intervals, difference with '{REFERENCE}' (paired bootstrap over the flights):")
    print(bootstrap.to_string())

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    path = REPORTS_DIR / f"{split}_results.md"
    path.write_text(
        f"# Results on the {split} flights\n\n"
        "Generated by `python -m opensky_eta.evaluate`. All errors are in minutes; the decision metric "
        "is the MAE, the MAE per flight segment and the 95th percentile are guardrails "
        "(see notebook 04, *Choice of the error metrics*).\n\n"
        f"## Errors\n\n{to_markdown(metrics.round(2).rename_axis('model'))}\n\n"
        f"## MAE with 95 % confidence intervals\n\n"
        f"Paired bootstrap over the {split} flights (1,000 resamples); the differences are computed "
        f"against *{REFERENCE}*, the best linear model.\n\n"
        f"{to_markdown(bootstrap.rename_axis('model'))}\n"
    )
    print(f"\nWritten to {path.relative_to(PROJECT_DIR)}")
    return metrics, bootstrap


if __name__ == "__main__":
    report(load_selected_models(), pd.read_parquet(FEATURES_PATH))
